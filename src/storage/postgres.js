// Postgres driver: the hosted collector. Takes a connection string (needs the `pg` package, loaded only here)
// or anything with query(text, params) -> { rows }, such as a pg.Pool you configured yourself.
// Every call returns a promise. The SQL is shared with SQLite (src/storage/sql.js); "?" becomes $1, $2, ...

const SCHEMA_V1 = `
CREATE TABLE orgs (id TEXT PRIMARY KEY, name TEXT NOT NULL, created_at BIGINT NOT NULL);
CREATE TABLE sites (id TEXT PRIMARY KEY, org_id TEXT NOT NULL REFERENCES orgs (id), name TEXT NOT NULL, created_at BIGINT NOT NULL);
CREATE INDEX sites_org ON sites (org_id);
CREATE TABLE api_keys (
  id TEXT PRIMARY KEY, site_id TEXT NOT NULL REFERENCES sites (id), hash TEXT NOT NULL UNIQUE, hint TEXT,
  created_at BIGINT NOT NULL, expires_at BIGINT, revoked_at BIGINT
);
CREATE INDEX api_keys_site ON api_keys (site_id);
CREATE TABLE site_configs (
  site_id TEXT NOT NULL REFERENCES sites (id), version INTEGER NOT NULL, config TEXT NOT NULL, source TEXT,
  created_at BIGINT NOT NULL, PRIMARY KEY (site_id, version)
);
CREATE TABLE sessions (
  site_id TEXT NOT NULL, code TEXT NOT NULL, created_at BIGINT NOT NULL, last_seen BIGINT NOT NULL,
  agent TEXT, vendor TEXT, kind TEXT, ip TEXT, ua TEXT, origin TEXT, intents TEXT,
  handoff_at BIGINT, handoff_referer TEXT, converted_at BIGINT, conversion_value DOUBLE PRECISION,
  PRIMARY KEY (site_id, code)
);
CREATE INDEX sessions_merge ON sessions (site_id, ip, agent, last_seen);
CREATE INDEX sessions_created ON sessions (site_id, created_at);
CREATE INDEX sessions_last_seen ON sessions (site_id, last_seen);
CREATE TABLE events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, site_id TEXT NOT NULL, ts BIGINT NOT NULL, code TEXT,
  type TEXT NOT NULL, actor TEXT, agent TEXT, vendor TEXT, ip TEXT, ua TEXT, method TEXT, path TEXT, query TEXT,
  status INTEGER, title TEXT, data TEXT
);
CREATE INDEX events_code ON events (site_id, code, ts);
CREATE INDEX events_ts ON events (site_id, ts);
CREATE INDEX events_type ON events (site_id, type, ts);
CREATE TABLE exposures (
  site_id TEXT NOT NULL, code TEXT NOT NULL, rule TEXT NOT NULL, arm TEXT NOT NULL, eligible INTEGER NOT NULL, ts BIGINT NOT NULL,
  PRIMARY KEY (site_id, code, rule)
);
CREATE INDEX exposures_ts ON exposures (site_id, ts);
CREATE TABLE answers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, site_id TEXT NOT NULL, run BIGINT NOT NULL, ts BIGINT NOT NULL,
  engine TEXT NOT NULL, model TEXT, question TEXT NOT NULL, answer TEXT, stop_reason TEXT, error TEXT, verdicts TEXT
);
CREATE INDEX answers_run ON answers (site_id, run, id);
`;

export const MIGRATIONS = [{ version: 1, sql: SCHEMA_V1 }];

/** COUNT and SUM come back as int8 / numeric; Wake's numbers fit in a double, so parse them as numbers. */
export function pgTypes(pg) {
  return { getTypeParser: (oid, format) => ([20, 1700].includes(oid) ? Number : pg.types.getTypeParser(oid, format)) };
}

const placeholders = new Map();
function toPg(sql) {
  let out = placeholders.get(sql);
  if (!out) {
    let i = 0;
    out = sql.replace(/\?/g, () => `$${++i}`);
    placeholders.set(sql, out);
  }
  return out;
}

export async function openPostgres(target, { now = () => Date.now(), migrate: runMigrations = true } = {}) {
  let pool = target;
  let owned = false;
  if (typeof target === 'string') {
    let pg;
    try { pg = (await import('pg')).default; } catch {
      throw new Error('wake: install the "pg" package to use Postgres (npm install pg)');
    }
    pool = new pg.Pool({ connectionString: target, types: pgTypes(pg), max: Number(process.env.WAKE_PG_POOL || 10) });
    owned = true;
  }
  const query = async (sql, params = []) => (await pool.query(toPg(sql), params)).rows;
  const driver = {
    dialect: 'postgres',
    raw: pool,
    all: (sql, params) => query(sql, params),
    get: async (sql, params) => (await query(sql, params))[0],
    run: async (sql, params) => { await query(sql, params); },
    exec: (sql) => pool.query(sql),
    close: async () => { if (owned) await pool.end(); },
  };
  if (runMigrations) await migrate(pool, now);
  return driver;
}

/** Apply pending migrations, one transaction each, holding an advisory lock so two collectors starting together don't race. */
async function migrate(pool, now) {
  const client = pool.connect ? await pool.connect() : pool;
  try {
    await client.query('SELECT pg_advisory_lock(7428301)');
    await client.query('CREATE TABLE IF NOT EXISTS schema_migrations (version INTEGER PRIMARY KEY, applied_at BIGINT NOT NULL)');
    const done = new Set((await client.query('SELECT version FROM schema_migrations')).rows.map((r) => Number(r.version)));
    for (const m of MIGRATIONS) {
      if (done.has(m.version)) continue;
      await client.query('BEGIN');
      try {
        await client.query(m.sql);
        await client.query('INSERT INTO schema_migrations (version, applied_at) VALUES ($1, $2)', [m.version, now()]);
        await client.query('COMMIT');
      } catch (err) {
        await client.query('ROLLBACK');
        throw err;
      }
    }
  } finally {
    await client.query('SELECT pg_advisory_unlock(7428301)').catch(() => {});
    client.release?.();
  }
}
